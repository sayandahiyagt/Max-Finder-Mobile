import { execFileSync } from "node:child_process";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import ts from "typescript";

// Local source inspection only. No application imports, credentials, or network calls.
const root = fileURLToPath(new URL("../", import.meta.url));
const tracked = execFileSync(
  "git",
  ["ls-files", "--cached", "--others", "--exclude-standard", "-z"],
  { cwd: root },
)
  .toString()
  .split("\0")
  .filter((path) => path && existsSync(new URL(`../${path}`, import.meta.url)))
  .sort();
const read = (path) =>
  readFileSync(new URL(`../${path}`, import.meta.url), "utf8");
const link = (path, line = 1) => `[${path}:${line}](../${path}#L${line})`;
const table = (headers, rows) =>
  [
    `| ${headers.join(" | ")} |`,
    `| ${headers.map(() => "---").join(" | ")} |`,
    ...rows.map((row) => `| ${row.join(" | ")} |`),
  ].join("\n");
const prismaModelNames = new Set(
  [...read("prisma/schema.prisma").matchAll(/^model (\w+)/gm)].map(
    ([, name]) => name[0].toLowerCase() + name.slice(1),
  ),
);
const prismaOperations = new Set([
  "aggregate",
  "count",
  "create",
  "createMany",
  "delete",
  "deleteMany",
  "findFirst",
  "findFirstOrThrow",
  "findMany",
  "findUnique",
  "findUniqueOrThrow",
  "groupBy",
  "update",
  "updateMany",
  "upsert",
]);
const sourcePaths = tracked.filter((path) => /^src\/.*\.tsx?$/.test(path));
const sources = sourcePaths.map((path) => {
  const text = read(path);
  const file = ts.createSourceFile(path, text, ts.ScriptTarget.Latest, true);
  const lines = text.trimEnd().split("\n");
  const calls = [];
  const prismaModels = [];
  const imports = [];
  function visit(node) {
    if (
      ts.isImportDeclaration(node) &&
      ts.isStringLiteral(node.moduleSpecifier)
    ) {
      imports.push(node.moduleSpecifier.text);
    }
    if (
      ts.isCallExpression(node) &&
      ts.isPropertyAccessExpression(node.expression) &&
      node.expression.name.text === "from" &&
      node.arguments[0] &&
      ts.isStringLiteral(node.arguments[0])
    ) {
      calls.push({
        target: node.arguments[0].text,
        storage: node.expression.expression.getText(file).includes(".storage"),
        line: file.getLineAndCharacterOfPosition(node.getStart(file)).line + 1,
      });
    }
    if (
      ts.isCallExpression(node) &&
      ts.isPropertyAccessExpression(node.expression) &&
      prismaOperations.has(node.expression.name.text) &&
      ts.isPropertyAccessExpression(node.expression.expression) &&
      prismaModelNames.has(node.expression.expression.name.text)
    ) {
      prismaModels.push({
        model: node.expression.expression.name.text,
        line: file.getLineAndCharacterOfPosition(node.getStart(file)).line + 1,
      });
    }
    ts.forEachChild(node, visit);
  }
  visit(file);
  return {
    path,
    text,
    imports,
    calls,
    prismaModels,
    lines: lines.length,
    longest: Math.max(...lines.map((line) => line.length)),
    client: /^['"]use client['"]/.test(text.trimStart()),
    serverAction: /^['"]use server['"]/.test(text.trimStart()),
  };
});
const migrations = tracked
  .filter((path) => /^supabase\/migrations\/.*\.sql$/.test(path))
  .map((path) => {
    const text = read(path);
    return {
      path,
      tables: [
        ...text.matchAll(
          /create\s+table\s+(?:if\s+not\s+exists\s+)?public\.([a-z_]+)/gi,
        ),
      ].map((match) => match[1]),
      policies: [...text.matchAll(/create\s+policy\s+/gi)].length,
    };
  });
const dataFiles = sources.filter((source) =>
  source.calls.some((call) => !call.storage),
);
const prismaFiles = sources.filter((source) => source.prismaModels.length > 0);
const providerFiles = sources.filter((source) =>
  source.imports.some(
    (name) =>
      name.startsWith("@supabase/") || name.startsWith("@/lib/supabase/"),
  ),
);
const testPaths = tracked.filter((path) =>
  /^tests\/.*\.test\.tsx?$/.test(path),
);
const tableDefinitions = new Map();
for (const migration of migrations) {
  for (const name of migration.tables) {
    tableDefinitions.set(name, [
      ...(tableDefinitions.get(name) ?? []),
      migration.path,
    ]);
  }
}
const sections = [
  "# Repository architecture inventory",
  "Generated by `node scripts/assess-repository.mjs --write`. Source inspection only. This script reads tracked and unignored working-tree files. It does not load the app, read environment files, contact services, or execute SQL.",
  "Counts and call locations support the assessment. They do not prove authorization, deployed schema state, runtime correctness, or unused code. SQL extraction is a text scan, not a PostgreSQL parser. Prisma model-call detection covers direct calls on generated model delegates and may miss indirect access. Import checks cover explicit imports, not transitive dependencies.",
  `Application TypeScript files: ${sources.length}. Files calling the Supabase Data API table interface: ${dataFiles.length}. Files calling Prisma model delegates: ${prismaFiles.length}. Files importing Supabase helpers or packages: ${providerFiles.length}. Test files: ${testPaths.length}. SQL migrations: ${migrations.length}.`,
  "## Application source coverage",
  "Every tracked or unignored application TypeScript file is listed. Longest line length helps locate compressed code. It is not a complexity score.",
  table(
    [
      "File",
      "Lines",
      "Longest line",
      "Client directive",
      "Server-action directive",
      "Supabase Data API targets",
    ],
    sources.map((source) => [
      link(source.path),
      source.lines,
      source.longest,
      source.client ? "yes" : "",
      source.serverAction ? "yes" : "",
      [
        ...new Set(
          source.calls
            .filter((call) => !call.storage)
            .map((call) => `\`${call.target}\``),
        ),
      ].join(", ") || "none",
    ]),
  ),
  "## Direct Supabase Data API table access",
  table(
    ["Location", "Table"],
    dataFiles.flatMap((source) =>
      source.calls
        .filter((call) => !call.storage)
        .map((call) => [link(source.path, call.line), `\`${call.target}\``]),
    ),
  ),
  "## Prisma model calls",
  table(
    ["File", "Models"],
    prismaFiles.map((source) => [
      link(source.path),
      [...new Set(source.prismaModels.map(({ model }) => `\`${model}\``))].join(
        ", ",
      ),
    ]),
  ),
  "## Explicit provider dependencies",
  table(
    ["File", "Imports"],
    providerFiles.map((source) => [
      link(source.path),
      source.imports
        .filter(
          (name) =>
            name.startsWith("@supabase/") || name.startsWith("@/lib/supabase/"),
        )
        .map((name) => `\`${name}\``)
        .join(", "),
    ]),
  ),
  "## Migration coverage",
  table(
    ["Migration", "Tables declared", "Policies created"],
    migrations.map((migration) => [
      link(migration.path),
      migration.tables.join(", ") || "none",
      migration.policies,
    ]),
  ),
  "## Tables declared by multiple migrations",
  "Multiple declarations require review. This alone does not prove replay failure because declarations may use IF NOT EXISTS.",
  table(
    ["Table", "Declaration files"],
    [...tableDefinitions]
      .filter(([, paths]) => paths.length > 1)
      .map(([name, paths]) => [
        `\`${name}\``,
        paths.map((path) => link(path)).join(", "),
      ]),
  ),
  "## Test coverage inventory",
  ...testPaths.map((path) => `- ${link(path)}`),
  "## Stylesheets",
  table(
    ["File", "Lines", "Longest line"],
    tracked
      .filter((path) => /^src\/.*\.css$/.test(path))
      .map((path) => {
        const lines = read(path).trimEnd().split("\n");
        return [
          link(path),
          lines.length,
          Math.max(...lines.map((line) => line.length)),
        ];
      }),
  ),
];
const output = `${sections.join("\n\n")}\n`;
if (process.argv.includes("--write")) {
  writeFileSync(
    new URL("../docs/architecture-inventory.md", import.meta.url),
    output,
  );
} else {
  process.stdout.write(output);
}
